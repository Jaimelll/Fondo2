INSERT INTO avance_beca (beca_id, etapa_id, fecha, sustento, monto, created_at, informe_impacto_id)
SELECT p.beca_id, p.etapa_id, p.fecha, p.sustento, p.monto, p.created_at, p.informe_impacto_id
FROM _pagos_activa_t p
WHERE NOT EXISTS (
  SELECT 1 FROM avance_beca a
  WHERE a.beca_id = p.beca_id AND a.fecha = p.fecha AND a.monto = p.monto
    AND coalesce(a.sustento, '') = coalesce(p.sustento, ''));

-- Recalculo (mismo criterio que recalculateBecaAvance; "hoy" en UTC)
WITH hoy AS (SELECT (now() AT TIME ZONE 'UTC')::date d),
ult AS (
  SELECT DISTINCT ON (a.beca_id) a.beca_id, a.etapa_id
  FROM avance_beca a, hoy
  WHERE a.beca_id IN (SELECT beca_id FROM _pagos_activa_t) AND a.fecha <= hoy.d
  ORDER BY a.beca_id, a.fecha DESC, a.id DESC),
tot AS (
  SELECT a.beca_id, sum(coalesce(a.monto, 0)) avance
  FROM avance_beca a, hoy
  WHERE a.beca_id IN (SELECT beca_id FROM _pagos_activa_t) AND a.fecha <= hoy.d
  GROUP BY a.beca_id)
UPDATE becas_nueva b SET etapa_id = ult.etapa_id, avance = tot.avance
FROM ult JOIN tot USING (beca_id)
WHERE b.id = ult.beca_id;

SELECT count(*) AS pagos_activa_t_en_fondo2, round(sum(a.monto), 2) AS total
FROM avance_beca a JOIN _pagos_activa_t p
  ON a.beca_id = p.beca_id AND a.fecha = p.fecha AND a.monto = p.monto
 AND coalesce(a.sustento, '') = coalesce(p.sustento, '');

COMMIT;
